func drawGridFont(frame []uint8, w, h, x, y int, text string, font map[rune][]string, color uint8, tracking int) int {
	cx := x
	for _, ch := range text {
		g, ok := font[ch]
		if !ok {
			g, ok = font[' ']
			if !ok {
				cx += 6
				continue
			}
		}
		gw := 0
		if len(g) > 0 {
			gw = len(g[0])
		}
		for r, row := range g {
			py := y + r
			if py < 0 || py >= h {
				continue
			}
			for c := 0; c < len(row); c++ {
				if row[c] == '1' {
					px := cx + c
					if px >= 0 && px < w {
						frame[py*w+px] = color
					}
				}
			}
		}
		cx += gw + tracking
	}
	return cx
}

func measureGridFont(text string, font map[rune][]string, tracking int) int {
	w := 0
	count := 0
	for _, ch := range text {
		g, ok := font[ch]
		if !ok {
			g = font[' ']
		}
		gw := 6
		if len(g) > 0 {
			gw = len(g[0])
		}
		w += gw + tracking
		count++
	}
	if count == 0 {
		return 0
	}
	return w - tracking
}

func drawGridFontRight(frame []uint8, w, h, rightX, y int, text string, font map[rune][]string, color uint8, tracking int) {
	tw := measureGridFont(text, font, tracking)
	drawGridFont(frame, w, h, rightX-tw, y, text, font, color, tracking)
}
